/// Execute a conditional symbology procedure by name.
///
/// # Arguments
/// * `procedure` - Procedure name like "DEPARE02" or "DEPCNT02"
/// * `feature` - The feature to process
/// * `settings` - Mariner settings
///
/// # Returns
/// Render instructions generated by the procedure, or None if unknown procedure.
pub fn execute_cs(
    procedure: &str,
    feature: &Feature,
    settings: &MarinerSettings,
    ctx: &CsContext,
) -> Option<Vec<RenderInstruction>> {
    match procedure {
        "DATCVR01" => Some(datcvr01_instructions(feature)),
        "DEPARE01" | "DEPARE02" => Some(depare02_instructions(feature, settings)),
        "DEPCNT02" => {
            let (pattern, width, color_token) = depcnt02_params(feature, settings, ctx.safety_contour);
            Some(vec![RenderInstruction::LineStyle {
                pattern,
                width,
                color: color_token.to_string(),
            }])
        }
        "SLCONS03" => Some(slcons03_instructions(feature, settings)),
        "QUAPOS01" => Some(quapos01_instructions(feature, settings)),
        "LIGHTS05" | "LIGHTS06" => {
            // light_render_info carries the flare's 135-degree rotation and the
            // ORIENT-derived rotation for directional lights; the instruction
            // stream is where that belongs, so the renderer has one source.
            // A light with a valid sector is drawn as a bounded arc, not a
            // symbol: s52cnsy.cpp LIGHTS06 replaces the symbol command with
            // CA(). Manx builds that arc in tiles/builder.rs from
            // light_sector_info, so the instruction stream carries nothing —
            // emitting the all-round symbol here would leave a ring the
            // renderer then has to throw away.
            if light_sector_info(feature).is_some() {
                return Some(Vec::new());
            }
            let info = light_render_info(feature, settings);
            Some(vec![RenderInstruction::Symbol {
                name: info.symbol_name.to_string(),
                rotation: info.rotation_deg.map(SymbolRotation::Degrees),
            }])
        }
        "OBSTRN04" => Some(obstrn04_instructions(feature, settings, ctx)),
        "WRECKS02" => Some(wrecks02_instructions(feature, settings, ctx)),
        "RESARE02" => Some(resare02_instructions(feature, settings)),
        "RESTRN01" => Some(restrn01_instructions(feature)),
        "QUALIN01" => Some(qualin01_instructions(feature)),
        "TOPMAR01" => Some(topmar01_instructions(feature, settings)),
        "SYMINS01" => Some(symins01_instructions(feature)),
        _ => None, // Unknown procedure
    }
}

/// SYMINS01: the feature carries its own symbology. A NEWOBJ — a virtual AIS
/// aid to navigation, or any object class newer than the presentation
/// library — states in its SYMINS attribute exactly what to draw, e.g.
/// `SY(BOYSAW12);TX('V-AIS',3,2,2,'15110',2,0,CHMGD,11)`, and s52cnsy.cpp
/// hands that string straight back as the rules. Without it a virtual
/// buoy marking a new wreck draws nothing at all.
///
/// A CS call inside SYMINS is dropped rather than run: chart data must not
/// be able to send the engine round in a loop.
fn symins01_instructions(feature: &Feature) -> Vec<RenderInstruction> {
    feature
        .attribute_str("SYMINS")
        .map(RenderInstruction::parse_all)
        .unwrap_or_default()
        .into_iter()
        .filter(|i| !matches!(i, RenderInstruction::ConditionalSymbology { .. }))
        .collect()
}

/// Check if an instruction string contains a CS procedure reference.
///
/// Returns Some(procedure_name) if found, None otherwise.
pub fn extract_cs_procedure(instruction: &str) -> Option<&str> {
    // Look for CS(PROCNAME) pattern
    if let Some(start) = instruction.find("CS(") {
        let rest = &instruction[start + 3..];
        if let Some(end) = rest.find(')') {
            return Some(&rest[..end]);
        }
    }
    None
}

