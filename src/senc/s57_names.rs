/// The full name of an S-57 object class, e.g. "Buoy, cardinal" for BOYCAR.
pub fn object_class_name(acronym: &str) -> Option<&'static str> {
    OBJECT_CLASSES
        .binary_search_by(|(a, _)| (*a).cmp(acronym))
        .ok()
        .map(|i| OBJECT_CLASSES[i].1)
}

/// The meaning of an enumerated attribute value, e.g. CATCAM 1 is
/// "North Cardinal Mark". `None` when the attribute is not an enumeration or
/// the value is not one the standard lists.
pub fn attribute_value_name(acronym: &str, value: u32) -> Option<&'static str> {
    ATTRIBUTE_VALUES
        .binary_search_by(|(a, v, _)| (*a, *v).cmp(&(acronym, value)))
        .ok()
        .map(|i| ATTRIBUTE_VALUES[i].2)
}

