    fn names_the_things_the_bubble_shows() {
        assert_eq!(object_class_name("BOYCAR"), Some("Buoy, cardinal"));
        assert_eq!(object_class_name("DEPARE"), Some("Depth area"));
        assert_eq!(object_class_name("NOSUCH"), None);
        assert_eq!(attribute_value_name("CATCAM", 1), Some("north cardinal mark"));
        assert_eq!(attribute_value_name("CATCAM", 99), None);
        assert_eq!(attribute_value_name("DRVAL1", 1), None);
    }
