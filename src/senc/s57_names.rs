    #[test]
    fn tables_are_sorted_for_binary_search() {
        for w in OBJECT_CLASSES.windows(2) {
            assert!(w[0].0 < w[1].0, "{} then {}", w[0].0, w[1].0);
        }
        for w in ATTRIBUTE_VALUES.windows(2) {
            assert!((w[0].0, w[0].1) < (w[1].0, w[1].1), "{:?} then {:?}", &w[0], &w[1]);
        }
    }

